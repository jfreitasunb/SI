    // The Get_module function allows to build the c_module-object
    // and needs to have the module's id like parameter. This function will
    //be get the data in the data-base and will put them in the object.     
    function get_module($idmodule)
    {
       $this->idmodule=$idmodule;
       //We get the module's datas
       $query="select * from module where idmodule=".$idmodule;
       $result=pg_query($query)or die(error());
       $array=pg_fetch_array($result);
       $this->idmodule = $array['idmodule'] ;
       $this->name     = $array['name']     ;
       $this->url      = $array['url']      ;
       $this->descr    = $array['descr']      ;   
       pg_free_result($result);
       //We get then all the modules functions
       $query="select funcname, funcurl from functions where idmodule=".$idmodule;
       $result=pg_query($query)or die(error());
       $count=pg_numrows($result);
       for ($i=0; $i<$count;$i++ )
       {
         $array=pg_fetch_array($result,$i);
         $this->funcarray[$i][0]=$array['funcname'];
         $this->funcarray[$i][1]=$array['funcurl'];
       }
       pg_free_result($result);
    }    

