  function create_header($url,$id)
  {
     if (!file_exists("../".$url) || !is_dir("../".$url))
     {
       mkdir("../".$url);
       //exec("mkdir "."../".$url);
       //echo exec("hostname");
       chmod ("../".$url, 0770);
     }  
     $fullname="../".$url."/".$url."_header.php"; 
     touch($fullname);
     chmod ($fullname, 0770);

     $fd=fopen($fullname,w);
     if (!fd)die(error("Creation du fichier impossible, veuiller reessayer ulterieurement ou contacter l'administrateur dy systeme."));

     //datas from the header_file
     fwrite($fd, "// This header is generated by the Manager System.\n");
     fwrite($fd, "// It must be inserted in the all files from your module.\n");
     fwrite($fd, "// It allows to execute the security's test.\n\n");
     fwrite($fd, "// Declaration of the modules variable.\n");
     fwrite($fd, "// This variable is used to identify a module in the securitys'functions.\n");
     $variable="\$idmodule=".$id;
     fwrite($fd, $variable."\n\n");
     $path="include(\"../../global/header.php\");";
     fwrite($fd, "// The security's tests.\n");
     fwrite($fd, $path."\n"); 
     
     fclose($fd);
   } 

